// Generates the /_components showcase demos from the official Graphite previews
// (design-system/graphite/components/<Name>/preview.html). Re-run when the DS changes:
//   pnpm --filter @sgs/prototype gen:showcase
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { listPreviews, readPreview } from '../../../packages/graphite/scripts/preview-to-module.mjs';

const app = join(dirname(fileURLToPath(import.meta.url)), '..');
const componentsDir = join(app, '../../design-system/graphite/components');
const out = join(app, 'src/showcase/demos');
rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });

const entries = [];
for (const name of listPreviews(componentsDir)) {
  const { meta, body } = readPreview(componentsDir, name);
  if (!body) continue; // Cover is static artwork, not a component demo.
  writeFileSync(join(out, name + '.ts'), `// @ts-nocheck -- demo code copied verbatim from the DS preview (untyped ES5).
// Generated by scripts/gen-showcase.mjs from design-system/graphite/components/${name}/preview.html. Do not edit by hand.
'use client';
import * as React from 'react';
import * as G from '@sgs/graphite';
const h = React.createElement;
${body}
`);
  entries.push(meta);
}

const dts = readFileSync(join(app, '../../packages/graphite/types/index.d.ts'), 'utf8');
const iconUnion = dts.match(/export type IconName = ([^;]+);/)[1];
const iconNames = [...iconUnion.matchAll(/'([^']+)'/g)].map((m) => m[1]);

const reg = `// Generated by scripts/gen-showcase.mjs. Do not edit by hand.
import type { ComponentType } from 'react';
import type { IconName } from '@sgs/graphite';

export const iconNames: IconName[] = ${JSON.stringify(iconNames)};
${entries.map((e, i) => `import D${i} from './demos/${e.name}';`).join('\n')}

export interface DemoEntry { name: string; group: string; height: number; width: number; page: boolean; description: string; Demo: ComponentType }

export const demos: DemoEntry[] = [
${entries.map((e, i) => `  { ...${JSON.stringify(e)}, Demo: D${i} },`).join('\n')}
];
`;
writeFileSync(join(app, 'src/showcase/registry.ts'), reg);
console.log(`Generated ${entries.length} showcase demos.`);
